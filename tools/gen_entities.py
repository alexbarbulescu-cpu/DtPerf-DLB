"""Generates telemetry entity classes (P = 5, 20, 50 properties) and the
hand-written-equivalent mappers that a source generator would emit."""
import sys
SIZES = [5, 20, 50]
# fixed leading fields every telemetry message carries
HEAD = [("AssetId", "int"), ("Tick", "long"), ("Vibration", "double"), ("Temperature", "double"), ("Running", "bool")]
CYCLE = ["double", "int", "double", "long", "bool", "double", "DateTime"]

def props(p):
    out = list(HEAD[:min(p, len(HEAD))])
    i = 0
    while len(out) < p:
        t = CYCLE[i % len(CYCLE)]
        out.append((f"F{len(out):02d}", t)); i += 1
    return out

cs = ["// <auto-generated/> by tools/gen_entities.py", "namespace DtPerf;", ""]
gm = ["// <auto-generated/> Equivalent of source-generator output (no reflection, no runtime codegen).",
      "#nullable enable", "using System.Collections.Generic;", "namespace DtPerf;", "", "public static class GeneratedMappers", "{"]
for p in SIZES:
    ps = props(p)
    cs.append(f"public sealed class Telemetry{p}")
    cs.append("{")
    for n, t in ps:
        init = " = default;" if t != "DateTime" else ""
        cs.append(f"    public {t} {n} {{ get; set; }}")
    cs.append("}")
    cs.append("")
    gm.append(f"    public static Telemetry{p} Map{p}(Dictionary<string, object?> d)")
    gm.append("    {")
    gm.append(f"        var t = new Telemetry{p}();")
    gm.append("        foreach (var kv in d)")
    gm.append("        {")
    gm.append("            switch (kv.Key)")
    gm.append("            {")
    for n, ty in ps:
        gm.append(f"                case \"{n}\": t.{n} = ({ty})kv.Value!; break;")
    gm.append("            }")
    gm.append("        }")
    gm.append("        return t;")
    gm.append("    }")
    gm.append("")
    gm.append(f"    public static Telemetry{p} MapLookup{p}(Dictionary<string, object?> d)")
    gm.append("    {")
    gm.append(f"        var t = new Telemetry{p}();")
    for n, ty in ps:
        gm.append(f"        if (d.TryGetValue(\"{n}\", out var v_{n})) t.{n} = ({ty})v_{n}!;")
    gm.append("        return t;")
    gm.append("    }")
    gm.append("")
gm.append("}")
open(sys.argv[1] + "/Entities.g.cs", "w").write("\n".join(cs) + "\n")
open(sys.argv[1] + "/GeneratedMappers.g.cs", "w").write("\n".join(gm) + "\n")
